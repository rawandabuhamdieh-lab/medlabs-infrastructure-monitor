/**
 * Strictly SELECT-only read-only Oracle monitoring queries.
 * - Zero DDL/DML/PLSQL execution.
 * - Zero SQL_TEXT / SQL_FULLTEXT inspection.
 * - Zero access to clinical, laboratory, patient, or application schema tables.
 * - Dynamic filtering uses Oracle bind parameters (:p1, :p2) only.
 */

const FORBIDDEN_SQL_PATTERN =
  /\b(INSERT|UPDATE|DELETE|MERGE|ALTER|CREATE|DROP|TRUNCATE|GRANT|REVOKE|EXEC|EXECUTE|CALL|BEGIN|DECLARE|DBMS_|UTL_|XP_|SQL_TEXT|SQL_FULLTEXT|PATIENT|LAB_RESULTS)\b/i;

export function validateReadOnlyOracleSql(sql: string): boolean {
  const trimmed = sql.trim();
  if (!/^SELECT\b/i.test(trimmed)) return false;
  if (trimmed.includes(';')) return false;
  if (FORBIDDEN_SQL_PATTERN.test(trimmed)) return false;
  return true;
}

export const ORACLE_READ_ONLY_QUERIES = {
  instanceOverview: `SELECT INSTANCE_NAME, HOST_NAME, VERSION, STATUS, DATABASE_STATUS,
         TO_CHAR(STARTUP_TIME, 'YYYY-MM-DD HH24:MI:SS') AS STARTUP_TIME_STR,
         ROUND((SYSDATE - STARTUP_TIME) * 24, 1) AS UPTIME_HOURS
  FROM V$INSTANCE`,

  databaseOverview: `SELECT NAME, DATABASE_ROLE, OPEN_MODE
  FROM V$DATABASE`,

  productVersionFallback: `SELECT BANNER FROM V$VERSION WHERE ROWNUM = 1`,

  sessionSummary: `SELECT COUNT(*) AS TOTAL_SESSIONS,
         SUM(CASE WHEN STATUS = 'ACTIVE' AND TYPE = 'USER' THEN 1 ELSE 0 END) AS ACTIVE_SESSIONS,
         SUM(CASE WHEN STATUS = 'INACTIVE' AND TYPE = 'USER' THEN 1 ELSE 0 END) AS INACTIVE_SESSIONS,
         SUM(CASE WHEN BLOCKING_SESSION IS NOT NULL THEN 1 ELSE 0 END) AS BLOCKING_SESSIONS
  FROM V$SESSION
  WHERE TYPE = 'USER'`,

  resourceLimits: `SELECT RESOURCE_NAME, CURRENT_UTILIZATION, MAX_UTILIZATION, LIMIT_VALUE
  FROM V$RESOURCE_LIMIT
  WHERE RESOURCE_NAME IN (:r1, :r2)`,

  longRunningQueries: `SELECT SID, SERIAL# AS SERIAL_NUM, SQL_ID, NVL(USERNAME, 'USER') AS USERNAME,
         NVL(SCHEMANAME, NVL(USERNAME, 'UNKNOWN')) AS SCHEMA_NAME,
         NVL(OSUSER, '') AS OS_USER, NVL(MACHINE, '') AS MACHINE,
         NVL(PROGRAM, '') AS PROGRAM, LAST_CALL_ET AS ELAPSED_SEC,
         NVL(EVENT, 'CPU') AS WAIT_EVENT, NVL(MODULE, 'Unknown') AS MODULE
  FROM V$SESSION
  WHERE STATUS = 'ACTIVE' AND TYPE = 'USER' AND LAST_CALL_ET > :minElapsedSec AND SQL_ID IS NOT NULL
  ORDER BY LAST_CALL_ET DESC`,

  sqlTextBySqlId: `SELECT SQL_ID, PARSING_SCHEMA_NAME, SUBSTR(SQL_TEXT, 1, 1000) AS SQL_TEXT
  FROM V$SQL
  WHERE SQL_ID = :sqlId AND ROWNUM = 1`,

  tablespaceUsageMetrics: `SELECT TABLESPACE_NAME,
         ROUND(USED_SPACE * 8192 / 1024 / 1024 / 1024, 2) AS USED_GB,
         ROUND(TABLESPACE_SIZE * 8192 / 1024 / 1024 / 1024, 2) AS MAX_GB,
         ROUND(USED_PERCENT, 1) AS USED_PCT
  FROM DBA_TABLESPACE_USAGE_METRICS
  ORDER BY USED_PERCENT DESC`,

  tablespaceDataFilesFallback: `SELECT df.TABLESPACE_NAME,
         ROUND((df.TOTAL_BYTES - NVL(fs.FREE_BYTES, 0)) / 1024 / 1024 / 1024, 2) AS USED_GB,
         ROUND(df.TOTAL_BYTES / 1024 / 1024 / 1024, 2) AS MAX_GB,
         ROUND(((df.TOTAL_BYTES - NVL(fs.FREE_BYTES, 0)) / NULLIF(df.TOTAL_BYTES, 0)) * 100, 1) AS USED_PCT
  FROM (SELECT TABLESPACE_NAME, SUM(BYTES) AS TOTAL_BYTES FROM DBA_DATA_FILES GROUP BY TABLESPACE_NAME) df
  LEFT JOIN (SELECT TABLESPACE_NAME, SUM(BYTES) AS FREE_BYTES FROM DBA_FREE_SPACE GROUP BY TABLESPACE_NAME) fs
    ON df.TABLESPACE_NAME = fs.TABLESPACE_NAME
  ORDER BY USED_PCT DESC`,

  datafilesSummary: `SELECT COUNT(*) AS FILE_COUNT,
         ROUND(SUM(BYTES) / 1024 / 1024 / 1024, 2) AS TOTAL_GB,
         ROUND(SUM(GREATEST(BYTES, MAXBYTES)) / 1024 / 1024 / 1024, 2) AS MAX_GB,
         SUM(CASE WHEN AUTOEXTENSIBLE = 'YES' THEN 1 ELSE 0 END) AS AUTOEXT_COUNT
  FROM DBA_DATA_FILES`,

  tempTablespaces: `SELECT TABLESPACE_NAME,
         ROUND(TABLESPACE_SIZE / 1024 / 1024 / 1024, 2) AS ALLOCATED_GB,
         ROUND(ALLOCATED_SPACE / 1024 / 1024 / 1024, 2) AS USED_GB,
         ROUND(FREE_SPACE / 1024 / 1024 / 1024, 2) AS FREE_GB
  FROM DBA_TEMP_FREE_SPACE`,

  fraUsage: `SELECT NAME,
         ROUND(SPACE_LIMIT / 1024 / 1024 / 1024, 2) AS SPACE_LIMIT_GB,
         ROUND(SPACE_USED / 1024 / 1024 / 1024, 2) AS SPACE_USED_GB,
         ROUND(SPACE_RECLAIMABLE / 1024 / 1024 / 1024, 2) AS SPACE_RECLAIMABLE_GB
  FROM V$RECOVERY_FILE_DEST`,

  pgaStat: `SELECT ROUND(VALUE / 1024 / 1024, 1) AS VALUE
  FROM V$PGASTAT
  WHERE NAME = :metricName`,

  sgaInfo: `SELECT NAME, BYTES
  FROM V$SGAINFO
  WHERE NAME IN (:n1, :n2)`,

  hostCpuMetric: `SELECT ROUND(VALUE, 1) AS VALUE
  FROM V$SYSMETRIC
  WHERE METRIC_NAME = :metricName AND GROUP_ID = 2 AND ROWNUM = 1`,

  sysstatMetrics: `SELECT NAME, VALUE
  FROM V$SYSSTAT
  WHERE NAME IN (:s1, :s2, :s3, :s4)`,

  sqlAreaAggregate: `SELECT NVL(SUM(EXECUTIONS), 0) AS TOTAL_EXECUTIONS,
         NVL(SUM(DISK_READS), 0) AS DISK_READS,
         NVL(SUM(BUFFER_GETS), 0) AS BUFFER_GETS,
         ROUND(AVG(CASE WHEN EXECUTIONS > 0 THEN ELAPSED_TIME / EXECUTIONS / 1000 ELSE NULL END), 2) AS AVG_ELAPSED_MS
  FROM V$SQLAREA`,

  topWaitEvents: `SELECT EVENT, TOTAL_WAITS, ROUND(TIME_WAITED_MICRO / 1000, 0) AS TIME_WAITED_MS
  FROM V$SYSTEM_EVENT
  WHERE WAIT_CLASS <> 'Idle'
  ORDER BY TIME_WAITED_MICRO DESC`,

  rmanBackups: `SELECT SESSION_KEY, INPUT_TYPE, STATUS,
         TO_CHAR(END_TIME, 'YYYY-MM-DD HH24:MI') AS END_STR,
         ROUND(ELAPSED_SECONDS / 60, 1) AS DURATION_MIN,
         ROUND(OUTPUT_BYTES / 1024 / 1024 / 1024, 2) AS SIZE_GB,
         ROUND((SYSDATE - END_TIME) * 24, 1) AS AGE_HOURS
  FROM V$RMAN_BACKUP_JOB_DETAILS
  ORDER BY START_TIME DESC`,
} as const;
